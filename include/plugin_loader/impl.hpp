// Core of plugin_loader. Everything here lives in libplugin_loader.so so that the
// host and every plugin library share ONE process-wide factory table.
//
// Not part of the user-facing API; ClassLoader / MultiLibraryClassLoader and the
// registration macro are the interface.
#pragma once

#include <string>
#include <type_traits>
#include <typeinfo>
#include <vector>

namespace plugin_loader
{

class ClassLoader;

enum class LogLevel { Debug = 0, Info, Warn, Error, None };

namespace impl
{

// printf-style logger writing to stderr. Threshold: PLUGIN_LOADER_LOG_LEVEL =
// debug | info | warn (default) | error | none.
void log(LogLevel level, const char * fmt, ...) __attribute__((format(printf, 2, 3)));

// ---- plugin registration -----------------------------------------------------
// Called from the static initializer generated by PLUGIN_REGISTER_CLASS, i.e.
// while a library is being dlopen()'d. The factory is attributed to the library
// and ClassLoader currently loading on this thread. If there is none, the
// library was opened by some other means (e.g. linked into the executable): the
// factory has no owner and the "non-pure plugin library" flag is raised.
void register_factory(
  const std::string & class_name, const std::string & base_class_name, void * (*create)());

template<class Derived, class Base>
void register_class(const std::string & class_name)
{
  static_assert(std::is_base_of<Base, Derived>::value, "Derived must derive from Base");
  register_factory(
    class_name, typeid(Base).name(), []() -> void * {return static_cast<Base *>(new Derived());});
}

// ---- queries / creation ------------------------------------------------------
// Classes registered for the base type that `loader` may create: those it owns,
// followed by those with no owner.
std::vector<std::string> available_classes(const std::string & base_class_name,
  const ClassLoader * loader);

// Returns a Base* (as void*). Throws CreateClassException.
void * create_instance(
  const std::string & base_class_name, const std::string & class_name, ClassLoader * loader);

// ---- library management ------------------------------------------------------
// Open `path` on behalf of `loader`. If somebody already opened it, `loader` is
// just granted access to its classes. Throws LibraryLoadException.
void load_library(const std::string & path, ClassLoader * loader);

// Revoke `loader`'s access. The library is closed once no loader holds it.
// Does nothing once a non-pure plugin library has been opened.
void unload_library(const std::string & path, ClassLoader * loader);

// True if the library is open AND every class it registered is owned by `loader`.
bool is_library_loaded(const std::string & path, const ClassLoader * loader);
bool is_library_loaded_by_anybody(const std::string & path);
std::vector<std::string> all_libraries_used_by(const ClassLoader * loader);

bool has_non_pure_plugin_library_been_opened();

}  // namespace impl
}  // namespace plugin_loader
